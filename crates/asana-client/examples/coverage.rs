//! Prints the coverage table in `docs/coverage.md`: every operation in the pinned specification,
//! from the generated index, with its method, path, OAuth scope, and whether it pages and may be
//! retried.
//!
//! ```text
//! cargo run -p asana-client --example coverage > docs/coverage.md
//! ```
//!
//! It needs no token and sends nothing.

use std::collections::BTreeMap;

use asana_client::openapi::endpoints::{OPERATIONS, OperationInfo};

fn main() {
    let mut by_tag: BTreeMap<&str, Vec<&OperationInfo>> = BTreeMap::new();
    for operation in OPERATIONS {
        by_tag.entry(operation.tag).or_default().push(operation);
    }
    let paged = OPERATIONS.iter().filter(|op| op.paginated).count();
    let scoped = OPERATIONS.iter().filter(|op| op.scope.is_some()).count();

    println!("# Coverage");
    println!();
    println!("Generated by `cargo run -p asana-client --example coverage > docs/coverage.md` from");
    println!("`asana_openapi::endpoints::OPERATIONS`. Do not edit by hand.");
    println!();
    println!(
        "{} operations in {} groups. {paged} return pages (`Paginated`); {scoped} name a granular \
         OAuth scope, and the rest need the `default` scope (full permissions).",
        OPERATIONS.len(),
        by_tag.len()
    );
    println!();
    println!(
        "Each operation is a descriptor in `asana_openapi::endpoints` named after its `operationId` in"
    );
    println!("UpperCamelCase (`getTask` is `GetTask`), sent with `client.send(..)`.");
    println!(
        "\"Retried\" means the client may send it again after a server error or a lost answer;"
    );
    println!("every operation is retried after a `429`.");
    for (tag, operations) in &by_tag {
        println!();
        println!("## {tag}");
        println!();
        println!("| Operation | Method and path | Scope | Pages | Retried |");
        println!("|---|---|---|---|---|");
        for op in operations {
            println!(
                "| `{}` | `{} {}` | {} | {} | {} |",
                op.operation_id,
                op.method.as_str(),
                op.route,
                op.scope.map_or_else(
                    || "`default`".to_owned(),
                    |scope| format!("`{}`", scope.as_str())
                ),
                if op.paginated { "yes" } else { "" },
                if op.idempotent { "yes" } else { "" },
            );
        }
    }
}
